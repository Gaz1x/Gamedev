/**
 * Параметры фаз сложности в классическом режиме.
 *
 * Отдельный файл, чтобы сложность правилась без правок игровой логики.
 * Каждые PHASE_SECONDS секунд игры начинается новая фаза — веток больше.
 * Фаза действует только в классике: в режиме букв ветка на каждом бревне.
 */

/** Сколько секунд идёт одна фаза сложности: веток становится больше. */
export const PHASE_SECONDS = 60;

/**
 * Шанс ветки на новом сегменте по фазам: индекс 0 — фаза 1, индекс 1 — фаза 2 и т. д.
 * Если фаз больше, чем записей, берётся последнее значение.
 */
export const PHASE_BRANCH_CHANCES: readonly number[] = [0.2, 0.38, 0.56, 0.74, 0.9];

/** Шанс ветки на новом сегменте для указанной фазы (фаза считается с 1). */
export function branchChanceForPhase(phase: number): number {
  const index = Math.min(Math.max(phase, 1), PHASE_BRANCH_CHANCES.length) - 1;
  return PHASE_BRANCH_CHANCES[index];
}
