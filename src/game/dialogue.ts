/**
 * Сценарий переговоров.
 *
 * Это чистые данные: сюда можно добавлять ходы, не трогая логику сцены.
 * В каждом ходу один «хороший» ответ (терпение +1, заложник свободен),
 * один нейтральный и один грубый (терпение падает).
 */

export interface Choice {
  /** Текст реплики дипломата. */
  readonly text: string;
  /** Изменение терпения лорда: плюс — он доволен, минус — злится. */
  readonly patience: number;
  /** Сколько заложников отпущено за этот ответ. */
  readonly freed: number;
  /** Ответ лорда на выбранную реплику. */
  readonly reply: string;
}

export interface Turn {
  /** Реплика лорда, на которую игрок выбирает ответ. */
  readonly lord: string;
  /** Ровно три варианта: обычно хороший, нейтральный и плохой. */
  readonly choices: readonly [Choice, Choice, Choice];
}

